const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = file => fs.readFileSync(path.join(__dirname, file), 'utf8');
const url = source => 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
(async () => {
  const timelineURL = url(read('../yard-3d/timeline.js'));
  const { Timeline, yearDates } = await import(timelineURL);
  const model = await import(url(read('../yard-3d/scenes/heartbeat-model.js').replace("'../timeline.js'", JSON.stringify(timelineURL))));
  assert.equal(yearDates(2024, '2026-11-01').length, 366);
  assert.equal(yearDates(2025, '2026-11-01').length, 365);
  const current = yearDates(2026, '2026-11-01'); assert.equal(current.at(-1), '2026-11-01'); assert.equal(current.length, 305);
  assert.throws(() => yearDates(2027, '2026-11-01'));
  const timeline = new Timeline(365);
  assert(!timeline.playing); timeline.advance(60); assert.equal(timeline.index, 0);
  timeline.play(); timeline.advance(30); assert.equal(timeline.index, 182);
  timeline.pause(); timeline.advance(100); assert.equal(timeline.index, 182);
  timeline.play(); timeline.advance(30); assert.equal(timeline.index, 364); assert(!timeline.playing);
  timeline.play(); assert.equal(timeline.index, 0);
  timeline.setSpeed(2); timeline.advance(30); assert.equal(timeline.index, 364); assert(!timeline.playing);
  timeline.seek(-10); assert.equal(timeline.index, 0); timeline.seek(9999); assert.equal(timeline.index, 364);
  assert.throws(() => timeline.setSpeed(0)); assert.throws(() => new Timeline(0));
  const single = new Timeline(1); single.play(); assert(!single.playing);
  const today = '2026-11-01', date = '2026-10-31';
  const logs = model.dateIndex([{ date, action: 'watered', plantId: 'tree' }, { date, action: 'covered' }, { date: '2027-01-01', action: 'watered' }], today);
  const wildlife = model.dateIndex([{ date, species: 'Robin' }], today), photos = model.dateIndex([{ date, key: 'plant.jpg' }], today);
  const weather = model.weatherMap([{ date, hi: 0, lo: -1, pcp: 0 }, { date: '2026-10-30', hi: null, lo: 20, pcp: null }]);
  const day = model.daySnapshot(date, weather, logs, wildlife, photos);
  assert.equal(day.watering.length, 1); assert.equal(day.logs.length, 2); assert.equal(day.wildlife[0].species, 'Robin'); assert.equal(day.photos[0].key, 'plant.jpg'); assert.equal(day.weather.pcp, 0); assert.equal(day.weather.hi, 0);
  const gap = model.daySnapshot('2026-10-29', weather, logs, wildlife, photos); assert.equal(gap.weather.pcp, null); assert.equal(gap.logs.length, 0);
  assert(!logs.has('2027-01-01'));
  const overviews = [{ plantId: 'tree', calendar: [{ s: 11, e: 2, c: '#123456', k: 'bare' }, { s: 4, e: 5, c: '#ff0000', k: 'bloom' }, { s: 1, e: 12, c: 'bad' }] }];
  assert.equal(model.seasonalWindows(overviews, 1)[0].k, 'bare'); assert.equal(model.seasonalWindows(overviews, 4)[0].k, 'bloom'); assert.equal(model.seasonalWindows(overviews, 8).length, 0);
  const media = [{ plantId: 'tree', key: 'public.jpg' }, { plantId: 'tree', key: 'hidden.jpg', hideFromGallery: true }, { plantId: 'yard', key: 'yard.jpg' }, { plantId: 'wishlist', key: 'wishlist.jpg' }];
  assert.deepEqual(model.permittedPhotos(media, [{ id: 'tree' }], false).map(row => row.key), ['public.jpg']);
  assert.deepEqual(model.permittedPhotos(media, [{ id: 'tree' }], true).map(row => row.key), ['public.jpg', 'yard.jpg']);
  assert.deepEqual(model.permittedPhotos(media, [], false, false), []);
  assert.deepEqual(model.stablePosition('tree'), model.stablePosition('tree'));
  assert(model.recordYears([[{ date: '2018-01-01' }, { date: '2027-01-01' }, { date: '2025-02-29' }]], today).includes(2018));
  assert(!model.recordYears([[{ date: '2027-01-01' }]], today).includes(2027));
  console.log('PASS heartbeat: 60-second playback, pause/resume/replay/speed/scrub, leap/current years, synchronized sources, expected seasonal windows, gaps and photo privacy');
})().catch(error => { console.error(error); process.exitCode = 1; });
